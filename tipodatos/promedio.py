# Constante
NUMERO_NOTAS = 3

# Variables
nota1 = float(input("Ingresa la primera nota: "))
nota2 = float(input("Ingresa la segunda nota: "))
nota3 = float(input("Ingresa la tercera nota: "))

# Cálculo
promedio = (nota1 + nota2 + nota3) / NUMERO_NOTAS

# Impresión
print(f"El promedio es: {promedio}")