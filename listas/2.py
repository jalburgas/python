#Acceder a elementos (índices)
#/////////////////////////////
frutas = ["manzana", "naranja", "uva", "pera"]

# Primer elemento (índice 0)
print(frutas[0])  # Salida: manzana

# Segundo elemento (índice 1)
print(frutas[1])  # Salida: naranja

# Último elemento (índice -1)
print(frutas[-1])  # Salida: pera

# Segundo desde el final (índice -2)
print(frutas[-2])  # Salida: uva