#not (NO)
#El operador not es un operador lógico que invierte (niega) un valor booleano:

#    Si el valor es True, not lo convierte en False

#   Si el valor es False, not lo convierte en True

x = 5

print(not x > 10)           # True (invierte False)
print(not x > 0)            # False (invierte True)