# == es igual que
# != diferente que
# > mayor que   
# < menor que
# >= mayor o igual que
# <= menor o igual que

#los operadores de comparación devuelven un valor booleano (True o False) dependiendo del resultado de la comparación.
# Igualdad (==)
print(5 == 5)    # True
print(5 == 3)    # False
print("hola" == "hola")  # True

# Desigualdad (!=)
print(5 != 3)    # True
print(5 != 5)    # False

# Mayor que (>)
print(10 > 5)    # True
print(3 > 7)     # False

# Menor que (<)
print(3 < 7)     # True
print(10 < 5)    # False

# Mayor o igual que (>=)
print(5 >= 5)    # True
print(8 >= 5)    # True
print(3 >= 5)    # False

# Menor o igual que (<=)
print(3 <= 5)    # True
print(5 <= 5)    # True
print(8 <= 5)    # False