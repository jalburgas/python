#Mayor o igual que (>=) - ¿Es más grande o igual?
# ¿Tienes la edad mínima para ver la película? (mínimo 12 años)
mi_edad = 12
edad_minima = 12
print(mi_edad >= edad_minima)  # True (sí, tienes justo 12)

# ¿Tu calificación es suficiente para pasar? (mínimo 60)
mi_nota = 75
nota_minima = 60
print(mi_nota >= nota_minima)  # True (75 es mayor que 60)

# ¿Pasaste con 50?
mi_nota = 50
print(mi_nota >= nota_minima)  # False (50 es menor que 60)