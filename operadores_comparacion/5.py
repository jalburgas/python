#Menor que (<) - ¿Es más pequeño?
# ¿Tienes menos dinero que tu amigo?
mi_dinero = 50
dinero_amigo = 100
print(mi_dinero < dinero_amigo)  # True (sí, 50 es menos que 100)

# ¿Tienes menos dinero que tu hermana?
dinero_hermana = 30
print(mi_dinero < dinero_hermana)  # False (no, 50 no es menos que 30)