#Iterar significa recorrer o revisar cada elemento de una secuencia (como una lista, tupla, diccionario, string, etc.) uno por uno, normalmente para realizar alguna operación con cada elemento.
#Concepto básico

#Imagina que tienes una lista de números y quieres mostrarlos en pantalla. Iterar sería ir elemento por elemento:
numeros = [10, 20, 30, 40, 50]

# Iterar sobre la lista
for numero in numeros:
    print(numero)

# Resultado:
# 10
# 20
# 30
# 40
# 50